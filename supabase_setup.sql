-- VLANesia - Supabase PostgreSQL schema
-- Jalankan seluruh isi file ini di Supabase Dashboard > SQL Editor > New query > Run.

create table if not exists public.sessions (
  id text primary key,
  alias text not null,
  class_name text not null default 'X TJKT',
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  session_id text not null references public.sessions(id) on delete cascade,
  scenario integer not null,
  level integer not null default 1,
  success boolean not null default false,
  score integer not null default 0 check (score between 0 and 100),
  hints_used integer not null default 0,
  error_type text,
  diagnosis text,
  created_at timestamptz not null default now()
);

create table if not exists public.evaluations (
  id bigint generated by default as identity primary key,
  session_id text not null references public.sessions(id) on delete cascade,
  score integer not null default 0 check (score between 0 and 100),
  correct integer not null default 0,
  total integer not null default 0,
  reflection_difficulty text,
  reflection_benefit text,
  created_at timestamptz not null default now()
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  session_id text not null references public.sessions(id) on delete cascade,
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);

create index if not exists idx_attempts_session on public.attempts(session_id);
create index if not exists idx_attempts_created on public.attempts(created_at desc);
create index if not exists idx_evaluations_session on public.evaluations(session_id);
create index if not exists idx_evaluations_created on public.evaluations(created_at desc);
create index if not exists idx_logs_session on public.activity_logs(session_id);

-- Frontend VLANesia TIDAK mengakses tabel Supabase secara langsung.
-- Seluruh akses data memakai backend Node dengan secret/service-role key.
-- Karena itu RLS diaktifkan tanpa policy public agar akses browser langsung ditolak.
alter table public.sessions enable row level security;
alter table public.attempts enable row level security;
alter table public.evaluations enable row level security;
alter table public.activity_logs enable row level security;

